package fuzz

import (
	"bytes"
	"testing"

	"github.com/figox/figox-protocol/pkg/protocol"
)

// FuzzDecodeFrame fuzzes the DecodeFrame function.
func FuzzDecodeFrame(f *testing.F) {
	// Add seeds
	f.Add([]byte{0x10, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x01, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00})
	f.Add([]byte{0x19, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x01, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00})

	f.Fuzz(func(t *testing.T, data []byte) {
		r := bytes.NewReader(data)
		_, _ = protocol.DecodeFrame(r)

		_, _ = protocol.DecodeFrameFromBytes(data)
	})
}
